using System.ComponentModel.DataAnnotations;

namespace BookingServiceApi;

public class CreateBookingRequest
{
    [Required] public Guid TableId { get; set; }

    /// <summary>Send it WITHOUT a time zone offset, e.g. 2026-11-20T19:00:00</summary>
    [Required] public DateTime StartTime { get; set; }

    [Range(1, 100)] public int GuestsCount { get; set; }

    // optional: if empty, the contacts from AuthService are used
    [MaxLength(100)] public string? GuestName { get; set; }
    [MaxLength(20)] public string? GuestPhone { get; set; }
    [MaxLength(256), EmailAddress] public string? GuestEmail { get; set; }

    /// <summary>A unique key of the request (for example a GUID generated by the client).</summary>
    [Required, MaxLength(100)] public string IdempotencyKey { get; set; } = "";
}

public class UpdateBookingRequest
{
    [Required] public Guid TableId { get; set; }
    [Required] public DateTime StartTime { get; set; }
    [Range(1, 100)] public int GuestsCount { get; set; }
}

public class BookingResponse
{
    public Guid Id { get; set; }
    public Guid TableId { get; set; }
    public DateTime StartTime { get; set; }
    public DateTime EndTime { get; set; }
    public int GuestsCount { get; set; }
    public string Status { get; set; } = "";
    public DateTime CreationDate { get; set; }
    public string ConfirmationCode { get; set; } = "";
}

/// <summary>IsNew = false means "this is a repeated request, the existing booking is returned".</summary>
public record CreateBookingResult(BookingResponse Booking, bool IsNew);
